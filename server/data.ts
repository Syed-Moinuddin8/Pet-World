// Helper to generate realistic branch stock levels for all products
export function generateInitialInventory(): BranchInventory[] {
  const inventory: BranchInventory[] = [];
  const branchIds = ['branch-1', 'branch-2', 'branch-3', 'branch-4', 'branch-5', 'branch-6'];
  const now = new Date().toISOString();

  // Deterministic realistic stock pattern
  INITIAL_PRODUCTS.forEach((product, idx) => {
    branchIds.forEach((bId, bIndex) => {
      // Calculate realistic stock
      // Some products will be intentionally low stock or near reorder level for demo!
      let qty = 15;
      if (idx === 0) {
        // Royal canin maxi: B1: 25, B2: 18, B3: 40, B4: 12, B5: 31, B6: 20 (as in prompt example)
        const map: Record<string, number> = {
          'branch-1': 25,
          'branch-2': 18,
          'branch-3': 40,
          'branch-4': 12,
          'branch-5': 31,
          'branch-6': 20,
        };
        qty = map[bId] || 20;
      } else if (idx === 2) {
        // Pedigree Adult: B1: 30, B2: 22, B3: 35, B4: 18, B5: 25, B6: 15
        const map: Record<string, number> = {
          'branch-1': 30,
          'branch-2': 22,
          'branch-3': 35,
          'branch-4': 18,
          'branch-5': 25,
          'branch-6': 15,
        };
        qty = map[bId] || 20;
      } else if (idx % 11 === 0) {
        // Low stock simulation in Branch 3 & 4
        qty = bIndex === 2 ? 3 : bIndex === 3 ? 2 : (idx * 3 + bIndex * 7) % 25 + 8;
      } else if (idx % 17 === 0) {
        // Out of stock in Branch 6
        qty = bIndex === 5 ? 0 : (idx * 4 + bIndex * 3) % 20 + 5;
      } else {
        qty = ((idx * 7 + bIndex * 13) % 35) + 6;
      }

      inventory.push({
        branchId: bId,
        productId: product.id,
        quantity: qty,
        lastUpdated: now,
      });
    });
  });

  return inventory;
}

