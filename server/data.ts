// Helper function to generate relative date and time
const getRelativeDate = (daysAgo: number, hour: number, minute: number): { date: string; time: string; timestamp: number } => {
  const now = new Date();
  now.setDate(now.getDate() - daysAgo);
  now.setHours(hour, minute, 0, 0);
  return {
    date: now.toISOString().split('T')[0],
    time: now.toLocaleTimeString('en-US', { hour: 'numeric', minute: '2-digit', second: '2-digit', hour12: true }),
    timestamp: now.getTime(),
  };
};

